// Draws the cells of a cell-sorted buffer that are in view and within [minD, maxD) (scaled by `det`, but not for the
// terrain) as merged runs, nearest rows first.
function drawCells(r, start, lo, hi, mar, indexed, verts, minD, maxD) {
  const cx = F[CX], cy = F[CY], cz = F[CZ], fx = F[FX], fy = F[FY], fz = F[FZ], rx = F[RX], rz = F[RZ], ux = F[UX], uy = F[UY], uz = F[UZ];
  const ds = indexed === 1 ? 1 : det * det;
  const tx = TANH * W / H, hw = CELLW * 0.5, ex = hw + mar, min2 = minD * minD * ds, max2 = maxD * maxD * ds;
  for (let k = 0; k < CELLS; k++) {
    const rw = rowOrd[k], row = rw * CELLS, pz = OZ + (rw + 0.5) * CELLW - cz, hz = max(abs(pz) - hw, 0);
    let run = -1;
    for (let x = 0; x <= CELLS; x++) {
      const c = row + x; let v = false;
      if (x < CELLS) {
        const l = lo[c], h = hi[c];
        if (l <= h) {
          const px = OX + (x + 0.5) * CELLW - cx, py = (l + h) * 0.5 - cy, ey = (h - l) * 0.5 + mar, hx = max(abs(px) - hw, 0), h2 = hx * hx + hz * hz;
          if (h2 < max2 && h2 >= min2) {
            const lim = px * fx + py * fy + pz * fz + ex * abs(fx) + ey * abs(fy) + ex * abs(fz);
            if (lim >= 0 && abs(px * rx + pz * rz) - ex * (abs(rx) + abs(rz)) <= lim * tx) v = abs(px * ux + py * uy + pz * uz) - ex * (abs(ux) + abs(uz)) - ey * abs(uy) <= lim * TANH;
          }
        }
      }
      if (v) { if (run < 0) run = c; } else if (run >= 0) {
        const a = start[run], n = start[c] - a;
        if (n > 0) { if (indexed === 1) r.drawIndexed(n * 6, 1, a * 6, 0, 0); else if (indexed) r.drawIndexed(indexed.ib.length, n, indexed.i0, indexed.v0, a); else r.draw(verts, n, 0, a); }
        run = -1;
      }
    }
  }
}
function render() {
  // camera basis (right vector is horizontal)
  const cx = F[CX], cy = F[CY], cz = F[CZ], pitch = F[PIT], yaw = F[YAW];
  const cp = cos(pitch), fy = sin(pitch), rx = cos(yaw), rz = sin(yaw), fx = cp * rz, fz = -cp * rx;
  const ux = -rz * fy, uy = rz * fx - rx * fz, uz = rx * fy;
  F[FX] = fx; F[FY] = fy; F[FZ] = fz; F[RX] = rx; F[RZ] = rz; F[UX] = ux; F[UY] = uy; F[UZ] = uz;
  const asp = W / H, sx = 1 / (TANH * asp), sy = 1 / TANH, m = UB;
  m[0] = rx * sx; m[4] = 0; m[8] = rz * sx; m[12] = -(rx * cx + rz * cz) * sx;
  m[1] = ux * sy; m[5] = uy * sy; m[9] = uz * sy; m[13] = -(ux * cx + uy * cy + uz * cz) * sy;
  m[2] = 0; m[6] = 0; m[10] = 0; m[14] = NEAR * F[PS];
  m[3] = fx; m[7] = fy; m[11] = fz; m[15] = -(fx * cx + fy * cy + fz * cz);
  m[32] = cx; m[33] = cy; m[34] = cz; m[35] = F[TIME];
  m[36] = rx; m[37] = 0; m[38] = rz; m[39] = TANH * asp;
  m[40] = ux; m[41] = uy; m[42] = uz; m[43] = TANH;
  m[44] = fx; m[45] = fy; m[46] = fz; m[47] = NEAR * F[PS];
  ERA.tick(); // the era's own numbers: the share of its second water at the camera, the exposure
  m[57] = RAYS; m[58] = det;
  Q.writeBuffer(ubo, 0, UB);
  WT[0] = F[TIME]; Q.writeBuffer(uboW, 0, WT);
  // what is see-through: far to near (the order changes little from frame to frame, so sorting it is cheap)
  for (let i = 0; i < GLASS.length; i++) {
    const k = GLASS[i], d = k.data, f = k.far, o = k.ord, n = k.n; if (!n) continue;
    for (let j = 0; j < n; j++) { const x = d[j * 8] - cx, y = d[j * 8 + 1] - cy, z = d[j * 8 + 2] - cz; f[j] = x * x + y * y + z * z; }
    for (let j = 1; j < n; j++) { const v = o[j]; let m = j - 1; while (m >= 0 && f[o[m]] < f[v]) { o[m + 1] = o[m]; m--; } o[m + 1] = v; }
    for (let j = 0; j < n; j++) { const s = o[j] * 8, t = j * 8; for (let q = 0; q < 8; q++) k.out[t + q] = d[s + q]; }
    Q.writeBuffer(k.buf, 0, k.out);
  }
  // animals with a simpler far mesh: near ones to the front of the buffer, far ones behind (ALOD above). A kind
  // with `far` leaves out what is further than that from the camera: its first three floats, widened by its
  // fourth (how far one animal strays from them)
  for (let i = 0; i < ALOD.length; i++) {
    const k = ALOD[i], d = k.data, out = k.out, lf = k.lodFrom * k.lodFrom, fr = k.far || 0, n = k.n; if (!n) continue;
    let a = 0, b = n * 8;
    for (let j = 0; j < n; j++) {
      const o = j * 8, x = d[o] - cx, y = d[o + 1] - cy, z = d[o + 2] - cz, dd = x * x + y * y + z * z;
      if (dd < lf) { for (let q = 0; q < 8; q++) out[a + q] = d[o + q]; a += 8; }
      else if (!fr || dd < (fr + d[o + 3]) * (fr + d[o + 3])) { b -= 8; for (let q = 0; q < 8; q++) out[b + q] = d[o + q]; }
    }
    k.nNear = a / 8; k.nFar0 = b / 8;
    Q.writeBuffer(k.buf, 0, k.out);
  }

  { let cr = floor((cz - OZ) / CELLW) | 0; cr = cr < 0 ? 0 : cr > CELLS - 1 ? CELLS - 1 : cr; let n = 0; rowOrd[n++] = cr; for (let d = 1; d < CELLS; d++) { if (cr - d >= 0) rowOrd[n++] = cr - d; if (cr + d < CELLS) rowOrd[n++] = cr + d; } }
  const e = device.createCommandEncoder();
  let slot = null;
  if (hasTS) { for (let i = 0; i < qRead.length; i++) if (!qRead[i].busy) { slot = qRead[i]; break; } }
  waterPass[0].timestampWrites = slot ? tsBegin : undefined;
  passPost.timestampWrites = slot ? tsEnd : undefined;
  // animated water texture + mips
  let r = e.beginRenderPass(waterPass[0]); r.setPipeline(pWater); r.setBindGroup(0, bgWater); r.draw(3); r.end();
  for (let i = 1; i < 5; i++) { r = e.beginRenderPass(waterPass[i]); r.setPipeline(pMip16); r.setBindGroup(0, waterBG[i - 1]); r.draw(3); r.end(); }
  // scene
  r = e.beginRenderPass(passScene);
  r.setBindGroup(0, bg0);
  r.setPipeline(pTerrain); r.setVertexBuffer(0, vbTerrain); r.setVertexBuffer(1, ibOne); r.setIndexBuffer(ibTerrain, 'uint32');
  drawCells(r, T.start, T.lo, T.hi, 1.5, 1, 0, 0, 240);
  // What the era draws, in its order (KINDS in tools.js). A kind is all drawn at once, or by culling cell up to its
  // distance, with its simpler mesh from lodFrom on. Nothing here knows what the kinds are, and nothing is allocated
  r.setVertexBuffer(0, vbMesh); r.setIndexBuffer(ibMesh, 'uint32');
  for (let i = 0, p = null; i < KINDS.length; i++) {
    const k = KINDS[i]; if (!k.n || k.glass) continue;
    if (k.pipe !== p) r.setPipeline(p = k.pipe);
    r.setVertexBuffer(1, k.buf);
    if (!k.cells) {
      if (k.lm) { if (k.nNear) r.drawIndexed(k.m.ib.length, k.nNear, k.m.i0, k.m.v0, 0); if (k.n - k.nFar0) r.drawIndexed(k.lm.ib.length, k.n - k.nFar0, k.lm.i0, k.lm.v0, k.nFar0); }
      else r.drawIndexed(k.m.ib.length, k.n, k.m.i0, k.m.v0, 0);
    }
    else if (k.lod) { drawCells(r, k.start, k.lo, k.hi, 3, k.m, 0, 0, k.lodFrom); drawCells(r, k.start, k.lo, k.hi, 3, k.lm, 0, k.lodFrom, k.far); }
    else drawCells(r, k.start, k.lo, k.hi, 3, k.m, 0, 0, k.far);
  }
  // leaves: 9-row blades up close, 5 rows mid-range, a decimated set far away
  r.setPipeline(pLeaf); r.setVertexBuffer(0, ibBig); drawCells(r, Wd.big.start, Wd.big.lo, Wd.big.hi, 5, false, 18, 0, 24);
  r.setPipeline(pLeaf5); drawCells(r, Wd.big.start, Wd.big.lo, Wd.big.hi, 5, false, 10, 24, 58);
  r.setPipeline(pLeafF); r.setVertexBuffer(0, ibBigF); drawCells(r, Wd.bigF.start, Wd.bigF.lo, Wd.bigF.hi, 5, false, 6, 58, 150);
  r.setPipeline(pLeafS); r.setVertexBuffer(0, ibSmall); drawCells(r, Wd.small.start, Wd.small.lo, Wd.small.hi, 1.5, false, 6, 0, 70);
  r.setPipeline(pSurf); r.draw(4);
  r.setPipeline(pBack); r.draw(4);
  // what is see-through, over all of that
  for (let i = 0; i < GLASS.length; i++) {
    const k = GLASS[i]; if (!k.n) continue;
    r.setPipeline(k.pipe); r.setVertexBuffer(0, vbMesh); r.setVertexBuffer(1, k.buf); r.drawIndexed(k.m.ib.length, k.n, k.m.i0, k.m.v0, 0);
  }
  // sprites, where the era has any
  if (nBub) { r.setPipeline(pBub); r.setVertexBuffer(0, ibBubbles); r.draw(4, nBub); }
  if (nGl) { r.setPipeline(pGl); r.setVertexBuffer(0, ibGl); r.draw(4, nGl); }
  if (nSnow) { r.setPipeline(pSnow); r.setVertexBuffer(0, ibSnowB); r.draw(4, nSnow); }
  r.end();
  // light shafts
  r = e.beginRenderPass(passRays); r.setPipeline(pRays); r.setBindGroup(0, bgRays); r.draw(3); r.end();
  r = e.beginRenderPass(passBlur); r.setPipeline(pRB); r.setBindGroup(0, bgBlur); r.draw(3); r.end();
  // bloom
  for (let i = 0; i < bloomPass.length; i++) {
    r = e.beginRenderPass(bloomPass[i]); r.setPipeline(i === 0 ? pDown0 : i < NB ? pDown : pUp); r.setBindGroup(0, bloomBG[i]); r.draw(3); r.end();
  }
  // composite
  passPost.colorAttachments[0].view = ctx.getCurrentTexture().createView();
  r = e.beginRenderPass(passPost); r.setPipeline(pPost); r.setBindGroup(0, bgPost); r.draw(3); r.end();
  if (slot) { e.resolveQuerySet(qs, 0, 2, qResolve, 0); e.copyBufferToBuffer(qResolve, 0, slot.b, 0, 16); }
  submitList[0] = e.finish();
  Q.submit(submitList);
  if (slot) { slot.busy = true; slot.b.mapAsync(GPUMapMode.READ).then(slot.done); }
}

// CS[j] = distance to the rock (metres, < 0 in water) at the camera + CE[3j..3j+2]: the camera, then ±0.375 m on
// each axis for the gradient
const CE = new Float64Array([0, 0, 0, .375, 0, 0, -.375, 0, 0, 0, .375, 0, 0, -.375, 0, 0, 0, .375, 0, 0, -.375]), CS = new Float64Array(7);
const cv = (x, y, z) => { const b = CI[(x >> 2) + CN * ((y >> 2) + NY / 4 * (z >> 2))]; return b > 1 ? CG[b * 64 - 128 + (x & 3) + 4 * (y & 3) + 16 * (z & 3)] : b * 254 - 127; };
function sd(j) {
  const x = (F[CX] + CE[j * 3] - OX) / VS - CO, y = (F[CY] + CE[j * 3 + 1] - OY) / VS, z = (F[CZ] + CE[j * 3 + 2] - OZ) / VS - CO;
  const ix = x | 0, iy = y | 0, iz = z | 0, u = x - ix, v = y - iy, a = cv(ix, iy, iz), b = cv(ix, iy + 1, iz), c = cv(ix, iy, iz + 1), d = cv(ix, iy + 1, iz + 1);
  const p = a + (cv(ix + 1, iy, iz) - a) * u, q = b + (cv(ix + 1, iy + 1, iz) - b) * u, r = c + (cv(ix + 1, iy, iz + 1) - c) * u, s = d + (cv(ix + 1, iy + 1, iz + 1) - d) * u;
  const e = p + (q - p) * v; CS[j] = (e + (r + (s - r) * v - e) * (z - iz)) / 127;
}
// Moves the camera by F[MX..MZ] in steps shorter than its radius (CR for a diver, times the size of the player F[PS]:
// so it can't pass through thin rock), pushing it back out after each step and dropping velocity into the rock, so it
// slides along. A small player swims faster than its size says (SIZES below), so a frame takes more steps for it: about
// 4 for a fish and 13 for a shrimp at full speed, each a few reads of the collision field.
const CR = 0.5;
function collide() {
  const cr = CR * F[PS], n = floor(sqrt(F[MX] * F[MX] + F[MY] * F[MY] + F[MZ] * F[MZ]) / (0.8 * cr)) + 1;
  for (let i = 0; i < n; i++) {
    F[CX] += F[MX] / n; F[CY] += F[MY] / n; F[CZ] += F[MZ] / n;
    for (let k = 0; k < 2; k++) {
      sd(0); const s = CS[0] + cr; if (s <= 0) break;
      for (let j = 1; j < 7; j++) sd(j);
      let gx = CS[1] - CS[2], gy = CS[3] - CS[4], gz = CS[5] - CS[6]; const l = sqrt(gx * gx + gy * gy + gz * gz);
      if (l < 0.075) break; // flat: deep in rock
      gx /= l; gy /= l; gz /= l; const vn = F[VX] * gx + F[VY] * gy + F[VZ] * gz;
      F[CX] -= gx * s; F[CY] -= gy * s; F[CZ] -= gz * s;
      if (vn > 0) { F[VX] -= gx * vn; F[VY] -= gy * vn; F[VZ] -= gz * vn; }
    }
  }
}

function frame(now) {
  requestAnimationFrame(frame);
  const dtr = now - F[LAST]; F[LAST] = now;
  let dt = dtr / 1000; if (dt > 0.1) dt = 0.1;
  // Dynamic resolution for 60 fps: every second (0.4 s behind the menu) scale the load by k
  if (dtr < 1e3 && (dynT += dtr) > 0 && (dynN++, dynT > (menu ? 400 : 1000))) {
    const a = dynT / dynN, g = dynGN ? dynG / dynGN : 0; let k = 1;
    // with GPU timing: keep it between 9.8 and 13.6 ms
    if (g) { if (g > 13.6 || g < 9.8) k = 11.7 / g; }
    // without: slow for two periods in a row means fewer pixels, and twice as long before trying to go back up
    else if (a > 17.6) { dynOk = 0; if (++dynBad > 1) { k = 15 / a; dynBad = 0; dynWait = min(dynWait * 2, 60); } }
    // at the display's rate there is no telling if there is room, so try a little more now and then
    else { dynBad = 0; if (a < 12.5) k = 15 / a; else if (++dynOk > dynWait) { k = 1.17; dynOk = 0; } }
    k = k < 0.5 ? 0.5 : k > 1.7 ? 1.7 : k; const top = min(PIXMAX, DW * DH), mid = max(top / 2, PIXMIN), was = pix + det;
    // too slow: pixels down to `mid` first, then draw distance, then the remaining pixels; faster goes back the same way
    if (k < 1 ? pix > mid || det <= DETMIN : pix < mid || det >= 1) {
      const end = k < 1 ? (det > DETMIN ? mid : PIXMIN) : det < 1 ? mid : top;
      pix *= k; if (k < 1 ? pix < end : pix > end) pix = end;
    } else { det *= sqrt(k); det = det < DETMIN ? DETMIN : det > 1 ? 1 : det; }
    if (was !== pix + det) keep('abyssal', [pix < top ? pix | 0 : '', det]); // nothing kept at full resolution
    dynN = dynT = dynG = dynGN = 0; resize();
  }
  F[TIME] += dt;
  {
    // touch: holding the finger away from where it went down keeps turning, like a joystick
    if (tId >= 0) {
      const tr = 4 / (innerWidth < innerHeight ? innerWidth : innerHeight); let jx = (tx - tx0) * tr, jy = (ty - ty0) * tr;
      jx = jx > 1 ? 1 : jx < -1 ? -1 : jx; jy = jy > 1 ? 1 : jy < -1 ? -1 : jy;
      lkx += jx * 1.5 * dt; lky += jy * dt;
    }
    // mouse look through two cascaded low-pass stages
    const kq = 1 - exp(-dt * 30); lkx += mdx * 0.0022; lky += mdy * 0.0022; mdx = 0; mdy = 0;
    const ax = lkx * kq, ay = lky * kq; lkx -= ax; lky -= ay; l2x += ax; l2y += ay;
    const dyw = l2x * kq, dpt = l2y * kq; l2x -= dyw; l2y -= dpt;
    const yaw = F[YAW] + dyw; let pitch = F[PIT] - dpt; pitch = pitch < -1.55 ? -1.55 : pitch > 1.55 ? 1.55 : pitch;
    const sp = (ks || tN > 1 ? 26 : 7) * F[PV], k = 1 - exp(-dt * 4.5), mf = tId >= 0 ? 0.7 : kf - kb, mr = kr - kl, mu = ku - kd, cp = cos(pitch), sy = sin(yaw), cw = cos(yaw);
    const vx = F[VX] + ((sy * cp * mf + cw * mr) * sp - F[VX]) * k, vy = F[VY] + ((sin(pitch) * mf + mu) * sp - F[VY]) * k, vz = F[VZ] + ((-cw * cp * mf + sy * mr) * sp - F[VZ]) * k;
    let x = F[CX] + vx * dt, y = F[CY] + vy * dt, z = F[CZ] + vz * dt;
    const rad = sqrt(x * x + z * z); if (rad > EDGE) { x *= EDGE / rad; z *= EDGE / rad; }
    y = y < BOTTOM ? BOTTOM : y > TOP ? TOP : y;
    F[YAW] = yaw; F[PIT] = pitch; F[VX] = vx; F[VY] = vy; F[VZ] = vz; F[MX] = x - F[CX]; F[MY] = y - F[CY]; F[MZ] = z - F[CZ];
    collide();
  }
  render();
  zoo();
  if (hud) {
    hN++; if (dtr > hMax) hMax = dtr; if (dtr < hMin) hMin = dtr; if (dtr > hPer * 1.5) { hLate++; hTot++; }
    F[HUDT] += dtr / 1000;
    if (F[HUDT] > 0.5) { info.textContent = `${(hN / F[HUDT]).toFixed(0)} fps  ·  worst frame ${hMax.toFixed(1)} ms  ·  late frames ${hLate} (total ${hTot})  ·  GPU ${F[GPU].toFixed(2)} ms  ·  ${W}x${H} (${W * 100 / DW | 0}%)`; F[HUDT] = 0; hPer = hMin; hN = 0; hMax = 0; hMin = 1e9; hLate = 0; }
  }
}

// ---------------------------------------------------------------- the size of the player (docs/briefs/scale.md)
// Diver, fish or shrimp: one factor for how far the camera keeps from rock (collide) and for what is cut off in front
// of it (the near plane in render). Nothing else changes: the world, the haze, the light, the swim limits and the
// reach of the zoo are the same at every size. The key C goes round the three, a label names the new size for two
// seconds, and the browser remembers it (quality.js).
// The speed (frame) has a factor of its own, the third number of a size: a fish and a shrimp swim much faster than a
// tenth and a hundredth of a diver (2.45 and 0.84 m a second, 9.1 and 3.1 with Shift). That is not how fast such a
// swimmer would be: at its true speed the way from one garden to the next takes minutes (Mario, 2026-11-17).
// A camera without a body sees the same from the same spot at every size: so on shrinking the player moves towards
// what it looks at, until that is as many times nearer as the player is smaller. What it looked at is then that many
// times larger on the screen, as it would be for a small swimmer. On growing it moves back the same way, as far as the
// water behind it lets it (at most 8 m)
const SIZES = [[1, 'Diver · 1.8 m', 1], [0.1, 'Fish · 18 cm', 0.35], [0.01, 'Shrimp · 1.8 cm', 0.12]], sizeTag = $('u');
let psz = PSZ, sizeT = 0;
F[PS] = SIZES[psz][0]; F[PV] = SIZES[psz][2];
// the distance to rock at a point (metres, below 0 in water), from the field of the collision
const rockAt = (x, y, z) => { const a = F[CX], b = F[CY], c = F[CZ]; F[CX] = x; F[CY] = y; F[CZ] = z; sd(0); F[CX] = a; F[CY] = b; F[CZ] = c; return CS[0]; };
// how far ahead the player looks at something: the exhibit the hint names (zoo.js), else the first rock along the
// view, up to 40 m. 0: nothing in sight
const ahead = () => {
  if (zKind >= 0) return ZF[4];
  for (let t = 0.02; t < 40;) { const d = rockAt(F[CX] + F[FX] * t, F[CY] + F[FY] * t, F[CZ] + F[FZ] * t); if (d > -0.01) return t; t += d < -0.06 ? -d * 0.8 : 0.04; }
  return 0;
};
// moves the camera up to `want` metres along the view (back where `want` is below 0), stopping where the rock would
// come nearer than `room`
const glide = (want, room) => {
  const dir = want < 0 ? -1 : 1, n = abs(want);
  let s = 0; while (s < n && rockAt(F[CX] + F[FX] * dir * (s + 0.01), F[CY] + F[FY] * dir * (s + 0.01), F[CZ] + F[FZ] * dir * (s + 0.01)) < -room) s += 0.01;
  F[CX] += F[FX] * dir * s; F[CY] += F[FY] * dir * s; F[CZ] += F[FZ] * dir * s;
};
const grow = () => {
  const t = ahead(), was = F[PS];
  psz = (psz + 1) % 3; F[PS] = SIZES[psz][0]; F[PV] = SIZES[psz][2]; keep('abyssalSize', psz);
  sizeTag.textContent = SIZES[psz][1]; sizeTag.className = 'on'; clearTimeout(sizeT); sizeT = setTimeout(() => { sizeTag.className = ''; }, 2000);
  const k = F[PS] / was; F[VX] = F[VY] = F[VZ] = 0;
  if (t > 0) glide(k < 1 ? t * (1 - k) : -min(t * (k - 1), 8), CR * F[PS]);
  // Grown next to rock, the camera is pushed out until it has its room again (a jump is fine), and never left inside
  for (let i = 0; i < 40; i++) { F[MX] = F[MY] = F[MZ] = 0; collide(); sd(0); if (CS[0] + CR * F[PS] < 1e-3) break; }
  for (let i = 0; i < 300; i++) { sd(0); if (CS[0] < -0.01) break; F[CY] += 0.1; }
};

// ---------------------------------------------------------------- input
const key = (e, v) => {
  switch (e.code) {
    case 'KeyW': kf = v; break; case 'KeyS': kb = v; break; case 'KeyA': kl = v; break; case 'KeyD': kr = v; break;
    case 'KeyE': ku = v; break; case 'KeyQ': kd = v; break; case 'ShiftLeft': case 'ShiftRight': ks = v; break;
    default: if (v && !e.repeat) {
      if (e.code === 'KeyH') { hud = !hud; hTot = 0; hPer = 1e9; info.textContent = ''; }
      else if (e.code === 'KeyM') mute();
      else if (e.code === 'Escape') ui(true);
      else if (e.code === 'Space') zooKey();
      else if (e.code === 'KeyC') grow();
    }
  }
};
// behind the menu only the stats and mute keys work
addEventListener('keydown', (e) => { if (menu && e.code !== 'KeyH' && e.code !== 'KeyM') return; sound(); key(e, 1); });
addEventListener('keyup', (e) => key(e, 0));
const release = () => { kf = kb = kl = kr = ku = kd = ks = 0; tId = -1; tN = 0; };
const capture = () => { sound(); const p = canvas.requestPointerLock({ unadjustedMovement: true }); if (p && p.catch) p.catch(() => canvas.requestPointerLock()).catch(() => 0); };
// A click on the scene captures the mouse and reads the card like Space does. Not a click that a touch left behind:
// a tap on the hint or the card ends as a click on the scene when they have gone by the time the finger lifts
canvas.addEventListener('click', (e) => { if (e.pointerType !== 'touch') { capture(); zooKey(); } });
addEventListener('mousemove', (e) => { if (document.pointerLockElement === canvas) { mdx += e.movementX; mdy += e.movementY; } });
addEventListener('blur', release);
const touch = (e) => {
  e.preventDefault(); sound(); tN = e.touches.length;
  let f = null, first = false; for (let i = 0; i < tN; i++) if (e.touches[i].identifier === tId) f = e.touches[i];
  if (!f) { tId = -1; if (tN) { f = e.touches[0]; tId = f.identifier; first = true; } }
  if (f) {
    // the touch axes turn with the page when it lies on its side
    const x = rot.matches ? f.clientY : f.clientX, y = rot.matches ? -f.clientX : f.clientY, s = 1100 / min(innerWidth, innerHeight);
    if (first) { tx0 = x; ty0 = y; } else { mdx += (x - tx) * s; mdy += (y - ty) * s; } // the view follows the finger at once
    tx = x; ty = y;
  }
};
for (const n of ['touchstart', 'touchmove', 'touchend', 'touchcancel']) canvas.addEventListener(n, touch, { passive: false });

